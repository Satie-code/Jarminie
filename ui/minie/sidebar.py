"""MinieSidebar — Minie Persona UI workstream.

The left navigation rail for Minie's warm, companion-style shell — the
sibling to `ui/jarvis/navigation_rail.py`'s own cold/technical rail. Same
page/action structural split that module's own docstring establishes
(mutually-exclusive pages vs. a momentary one-shot action) but reskinned
for Minie's "rounded corners, soft glow, gentle language" visual language
(`presentation/minie_theme.py`'s own docstring) instead of Jarvis's sharp
holographic accent bar.

Seven rows: Home/Chat/Tasks/Calendar/Wellness/Reminders are mutually
exclusive pages (`page_selected`, carrying the literal page-id `str`
rather than an enum on the wire — nothing downstream in this workstream
needs the enum itself, only the id it names); Settings is a separate
one-shot action (`settings_requested`), never staying "checked" after
firing, the identical shape NavigationRail's own System/Code/Settings
rows already establish.

Pure static chrome: no QTimer, no CoreManager-polled data at all — just
one one-time construction-time read of `PresentationConfig.minie_ui_accent`
(the persona-identity-locked active-row glow color, never polled — the
same "read once at construction" rule this workstream's own shared
context establishes for identity-locked config values, matching
`presentation/minie_theme.py`'s own PRIMARY_ACCENT/GLOW docstring)."""

import math
from enum import Enum

from PySide6.QtCore import QPointF, QRectF, Qt, Signal
from PySide6.QtGui import QColor, QFont, QPainter, QPainterPath, QPen
from PySide6.QtWidgets import (
    QAbstractButton,
    QButtonGroup,
    QFrame,
    QHBoxLayout,
    QLabel,
    QVBoxLayout,
    QWidget,
)

from core.logging_setup import get_logger
from core.manager import CoreManager
from presentation import minie_theme

logger = get_logger(__name__)

_ICON_SIZE = 18.0
_ROW_HEIGHT = 44
_ROW_RADIUS = 14.0


class NavItem(Enum):
    HOME = "home"
    CHAT = "chat"
    TASKS = "tasks"
    CALENDAR = "calendar"
    WELLNESS = "wellness"
    REMINDERS = "reminders"
    SETTINGS = "settings"


_LABELS: dict[NavItem, str] = {
    NavItem.HOME: "Home",
    NavItem.CHAT: "Chat",
    NavItem.TASKS: "Tasks",
    NavItem.CALENDAR: "Calendar",
    NavItem.WELLNESS: "Wellness",
    NavItem.REMINDERS: "Reminders",
    NavItem.SETTINGS: "Settings",
}

PAGE_ITEMS: tuple[NavItem, ...] = (
    NavItem.HOME,
    NavItem.CHAT,
    NavItem.TASKS,
    NavItem.CALENDAR,
    NavItem.WELLNESS,
    NavItem.REMINDERS,
)


def _paint_icon(painter: QPainter, item: NavItem, rect: QRectF, color: QColor) -> None:
    """One small, self-painted line-art glyph per row — no image assets/
    icon fonts, the identical "the UI must be generated by the
    application itself" precedent `ui/jarvis/navigation_rail.py`'s own
    module-level `_paint_icon()` already establishes, applied here to
    Minie's own seven rows rather than reused directly (the icon
    vocabulary itself — house, speech bubble, calendar, heart, bell — is
    specific to this rail's own labels)."""
    pen = QPen(color)
    pen.setWidthF(1.4)
    pen.setCapStyle(Qt.PenCapStyle.RoundCap)
    pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
    painter.setPen(pen)
    painter.setBrush(Qt.BrushStyle.NoBrush)
    cx, cy = rect.center().x(), rect.center().y()
    half = rect.width() / 2.0

    if item is NavItem.HOME:
        painter.drawLine(QPointF(cx - half * 0.9, cy + half * 0.05), QPointF(cx, cy - half * 0.85))
        painter.drawLine(QPointF(cx, cy - half * 0.85), QPointF(cx + half * 0.9, cy + half * 0.05))
        painter.drawRect(QRectF(cx - half * 0.55, cy + half * 0.05, half * 1.1, half * 0.85))
    elif item is NavItem.CHAT:
        bubble = QRectF(cx - half * 0.85, cy - half * 0.65, half * 1.7, half * 1.15)
        painter.drawRoundedRect(bubble, 4, 4)
        painter.drawLine(
            QPointF(cx - half * 0.35, cy + half * 0.5), QPointF(cx - half * 0.6, cy + half * 0.9)
        )
    elif item is NavItem.TASKS:
        box = QRectF(cx - half * 0.75, cy - half * 0.75, half * 1.5, half * 1.5)
        painter.drawRoundedRect(box, 3, 3)
        painter.drawLine(
            QPointF(cx - half * 0.4, cy), QPointF(cx - half * 0.05, cy + half * 0.35)
        )
        painter.drawLine(
            QPointF(cx - half * 0.05, cy + half * 0.35), QPointF(cx + half * 0.5, cy - half * 0.35)
        )
    elif item is NavItem.CALENDAR:
        box = QRectF(cx - half * 0.85, cy - half * 0.7, half * 1.7, half * 1.4)
        painter.drawRoundedRect(box, 3, 3)
        painter.drawLine(
            QPointF(box.left(), cy - half * 0.15), QPointF(box.right(), cy - half * 0.15)
        )
        painter.drawLine(
            QPointF(cx - half * 0.4, box.top() - half * 0.15),
            QPointF(cx - half * 0.4, box.top() + half * 0.15),
        )
        painter.drawLine(
            QPointF(cx + half * 0.4, box.top() - half * 0.15),
            QPointF(cx + half * 0.4, box.top() + half * 0.15),
        )
    elif item is NavItem.WELLNESS:
        path = QPainterPath()
        path.moveTo(cx, cy + half * 0.7)
        path.cubicTo(
            cx - half * 1.1,
            cy + half * 0.1,
            cx - half * 0.65,
            cy - half * 0.9,
            cx,
            cy - half * 0.25,
        )
        path.cubicTo(
            cx + half * 0.65, cy - half * 0.9, cx + half * 1.1, cy + half * 0.1, cx, cy + half * 0.7
        )
        painter.drawPath(path)
    elif item is NavItem.REMINDERS:
        painter.drawArc(
            QRectF(cx - half * 0.65, cy - half * 0.8, half * 1.3, half * 1.3), 0, 180 * 16
        )
        painter.drawLine(
            QPointF(cx - half * 0.65, cy - half * 0.15), QPointF(cx - half * 0.85, cy + half * 0.35)
        )
        painter.drawLine(
            QPointF(cx + half * 0.65, cy - half * 0.15), QPointF(cx + half * 0.85, cy + half * 0.35)
        )
        painter.drawLine(
            QPointF(cx - half * 0.85, cy + half * 0.35), QPointF(cx + half * 0.85, cy + half * 0.35)
        )
        painter.drawEllipse(QPointF(cx, cy + half * 0.6), half * 0.12, half * 0.12)
    elif item is NavItem.SETTINGS:
        painter.drawEllipse(rect.center(), half * 0.45, half * 0.45)
        for tick in range(6):
            angle = tick * (math.pi / 3.0)
            inner = QPointF(cx + math.cos(angle) * half * 0.55, cy + math.sin(angle) * half * 0.55)
            outer = QPointF(cx + math.cos(angle) * half * 0.9, cy + math.sin(angle) * half * 0.9)
            painter.drawLine(inner, outer)


class _HeartGlyph(QWidget):
    """Self-painted filled heart mark — the sidebar's own top-of-branding
    glyph, matching this codebase's own "no image assets/icon fonts...
    generated by the application itself" precedent
    (`ui/jarvis/navigation_rail.py`'s own `_paint_icon` docstring) rather
    than a bundled icon file or an icon-font glyph."""

    def __init__(self, color: str, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self._color = QColor(color)
        self.setFixedSize(34, 30)

    def paintEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        painter.setPen(Qt.PenStyle.NoPen)
        painter.setBrush(self._color)
        w, h = float(self.width()), float(self.height())
        path = QPainterPath()
        path.moveTo(w / 2, h * 0.92)
        path.cubicTo(-w * 0.15, h * 0.55, w * 0.12, -h * 0.08, w / 2, h * 0.32)
        path.cubicTo(w * 0.88, -h * 0.08, w * 1.15, h * 0.55, w / 2, h * 0.92)
        painter.drawPath(path)
        painter.end()


class _MinieNavButton(QAbstractButton):
    """Self-painted nav row: icon + label, a glowing pink/purple glass
    capsule when checked (Minie's own "translucent glass panels...
    subtle neon glow" visual language, `presentation/minie_theme.py`'s
    own docstring) rather than NavigationRail's own sharp accent bar; a
    gentle low-opacity tint on hover. QAbstractButton (not QPushButton)
    for the identical reason `_NavButton`'s own docstring gives: every
    visual aspect here is custom-painted, so starting from QPushButton
    would mean fighting its own default chrome."""

    def __init__(self, item: NavItem, accent_color: str, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self._item = item
        self._hovered = False
        self._accent_color = accent_color
        self.setText(_LABELS[item])
        self.setCursor(Qt.CursorShape.PointingHandCursor)
        self.setFixedHeight(_ROW_HEIGHT)

    def enterEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        self._hovered = True
        self.update()
        super().enterEvent(event)

    def leaveEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        self._hovered = False
        self.update()
        super().leaveEvent(event)

    def paintEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        rect = QRectF(self.rect()).adjusted(8, 3, -8, -3)
        accent = QColor(self._accent_color)

        if self.isChecked():
            glow_fill = QColor(accent)
            glow_fill.setAlpha(46)
            painter.setPen(QPen(accent, 1.2))
            painter.setBrush(glow_fill)
            painter.drawRoundedRect(rect, _ROW_RADIUS, _ROW_RADIUS)
            text_color = QColor(minie_theme.TEXT_PRIMARY)
            icon_color = accent
        elif self._hovered and self.isEnabled():
            hover_fill = QColor(accent)
            hover_fill.setAlpha(18)
            painter.setPen(Qt.PenStyle.NoPen)
            painter.setBrush(hover_fill)
            painter.drawRoundedRect(rect, _ROW_RADIUS, _ROW_RADIUS)
            text_color = QColor(minie_theme.TEXT_PRIMARY)
            icon_color = QColor(minie_theme.TEXT_PRIMARY)
        else:
            painter.setPen(Qt.PenStyle.NoPen)
            painter.setBrush(Qt.BrushStyle.NoBrush)
            text_color = QColor(minie_theme.TEXT_SECONDARY)
            icon_color = QColor(minie_theme.TEXT_SECONDARY)

        icon_rect = QRectF(
            rect.left() + 12, rect.top() + (rect.height() - _ICON_SIZE) / 2, _ICON_SIZE, _ICON_SIZE
        )
        _paint_icon(painter, self._item, icon_rect, icon_color)

        font = QFont(minie_theme.FONT_FAMILY)
        font.setPointSize(10)
        font.setBold(self.isChecked())
        painter.setFont(font)
        painter.setPen(text_color)
        text_left = icon_rect.right() + 12
        text_rect = QRectF(text_left, rect.top(), rect.right() - text_left - 8, rect.height())
        alignment = int(Qt.AlignmentFlag.AlignVCenter | Qt.AlignmentFlag.AlignLeft)
        painter.drawText(text_rect, alignment, self.text())
        painter.end()


class MinieSidebar(QWidget):
    """Constructor DI: only CoreManager, for the one one-time
    construction-time read of `presentation_config().minie_ui_accent` —
    see this module's own docstring for why it is never polled."""

    page_selected = Signal(str)
    settings_requested = Signal()

    def __init__(self, core_manager: CoreManager, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        try:
            accent_color = core_manager.presentation_config().minie_ui_accent
        except Exception:
            logger.exception(
                "MinieSidebar failed to read the persona accent color; using the default."
            )
            accent_color = minie_theme.PRIMARY_ACCENT_DEFAULT

        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 12, 0, 12)
        layout.setSpacing(2)
        layout.addLayout(self._build_branding(accent_color))
        layout.addSpacing(18)

        self._buttons: dict[str, _MinieNavButton] = {}
        self._page_group = QButtonGroup(self)
        self._page_group.setExclusive(True)

        for item in PAGE_ITEMS:
            button = _MinieNavButton(item, accent_color)
            button.setCheckable(True)
            self._page_group.addButton(button)
            button.clicked.connect(lambda _checked, i=item: self.page_selected.emit(i.value))
            layout.addWidget(button)
            self._buttons[item.value] = button

        layout.addStretch(1)

        self._settings_button = _MinieNavButton(NavItem.SETTINGS, accent_color)
        self._settings_button.clicked.connect(self.settings_requested.emit)
        layout.addWidget(self._settings_button)

        self.set_active_page("home")

    def _build_branding(self, accent_color: str) -> QVBoxLayout:
        branding = QVBoxLayout()
        branding.setSpacing(2)
        branding.setContentsMargins(16, 0, 16, 0)

        heart_row = QHBoxLayout()
        heart_row.addStretch(1)
        heart_row.addWidget(_HeartGlyph(accent_color))
        heart_row.addStretch(1)
        branding.addLayout(heart_row)

        title = QLabel("MINIE")
        title_font = QFont(minie_theme.FONT_FAMILY)
        title_font.setPointSize(20)
        title_font.setBold(True)
        title.setFont(title_font)
        title.setAlignment(Qt.AlignmentFlag.AlignHCenter)
        title.setStyleSheet(f"color: {minie_theme.TEXT_PRIMARY};")
        branding.addWidget(title)

        subtitle = QLabel("Your Cute AI Companion")
        subtitle_font = QFont(minie_theme.FONT_FAMILY)
        subtitle_font.setPointSize(8)
        subtitle.setFont(subtitle_font)
        subtitle.setAlignment(Qt.AlignmentFlag.AlignHCenter)
        subtitle.setStyleSheet(f"color: {minie_theme.TEXT_SECONDARY};")
        branding.addWidget(subtitle)

        branding.addSpacing(12)
        divider = QFrame()
        divider.setFrameShape(QFrame.Shape.HLine)
        divider.setFixedHeight(1)
        divider.setStyleSheet(f"background-color: {minie_theme.BORDER_DIM}; border: none;")
        branding.addWidget(divider)

        return branding

    def set_active_page(self, page_id: str) -> None:
        """Sets which row shows the active glass-capsule state WITHOUT
        emitting `page_selected` — so external code (e.g. a "Home"
        shortcut button elsewhere in the shell) can sync the sidebar's
        own highlight without triggering a second, redundant page swap.
        An unrecognized page_id is logged and otherwise ignored rather
        than raising — this method has no safe way to "fail loudly"
        without risking a crash from what would only ever be a caller
        typo, never a data-driven value."""
        button = self._buttons.get(page_id)
        if button is None:
            logger.warning("MinieSidebar.set_active_page called with unknown page_id=%r.", page_id)
            return
        button.setChecked(True)
