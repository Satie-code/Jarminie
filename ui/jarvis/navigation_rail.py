"""NavigationRail — JARVIS Holographic HUD reskin, Phase 2.

The brief's own Left Navigation Rail: Dashboard / Conversation / Memory /
Tasks / System / Code / Settings, minimal line icons (drawn procedurally
via QPainter below — no image assets/icon fonts, per section 30's "the
UI must be generated by the application itself"), with a distinct
active/hover/disabled visual state per row.

Two different behaviors live behind these seven rows, and this module
keeps them structurally separate rather than treating all seven as one
uniform list:

- Dashboard/Conversation/Memory/Tasks are **pages** — mutually exclusive,
  checkable, one always active (`page_selected` signal; HudShell swaps
  its center content in response — see this workstream's scope decision:
  only Dashboard has real content, the other three get an honest
  "Coming soon" placeholder).
- System/Code/Settings are **actions** — momentary, never "stay checked"
  after firing (`system_requested`/`code_requested`/`settings_requested`
  signals; MainWindow already has real handlers for System/Settings —
  `_open_runtime_diagnostics()`/`_open_settings()` — so this phase wires
  those two directly. Code has no backend to call yet (ActionRegistry
  isn't reachable from ui/ until Phase 4's own plumbing) — its button is
  built disabled with an honest tooltip rather than wired to a no-op,
  and Phase 4 enables it for real via `set_code_action_enabled()`.
"""

import math
from enum import Enum

from PySide6.QtCore import QPointF, QRectF, Qt, Signal
from PySide6.QtGui import QColor, QPainter, QPen
from PySide6.QtWidgets import QAbstractButton, QButtonGroup, QVBoxLayout, QWidget

from presentation import theme

_ICON_SIZE = 18.0
_ROW_HEIGHT = 40
_ACTIVE_BAR_WIDTH = 3


class NavItem(Enum):
    DASHBOARD = "dashboard"
    CONVERSATION = "conversation"
    MEMORY = "memory"
    TASKS = "tasks"
    SYSTEM = "system"
    CODE = "code"
    SETTINGS = "settings"


_LABELS: dict[NavItem, str] = {
    NavItem.DASHBOARD: "Dashboard",
    NavItem.CONVERSATION: "Conversation",
    NavItem.MEMORY: "Memory",
    NavItem.TASKS: "Tasks",
    NavItem.SYSTEM: "System",
    NavItem.CODE: "Code",
    NavItem.SETTINGS: "Settings",
}

PAGE_ITEMS: tuple[NavItem, ...] = (
    NavItem.DASHBOARD,
    NavItem.CONVERSATION,
    NavItem.MEMORY,
    NavItem.TASKS,
)


def _paint_icon(painter: QPainter, item: NavItem, rect: QRectF, color: QColor) -> None:
    """A small, deliberately plain geometric glyph per NavItem — plain
    QPainter primitives only (drawLine/drawRect/drawEllipse), never a
    decorative or cartoonish shape, per the brief's own "minimal
    futuristic line icons" wording."""
    pen = QPen(color)
    pen.setWidthF(1.4)
    pen.setCapStyle(Qt.PenCapStyle.RoundCap)
    painter.setPen(pen)
    painter.setBrush(Qt.BrushStyle.NoBrush)
    cx, cy = rect.center().x(), rect.center().y()
    half = rect.width() / 2.0

    if item is NavItem.DASHBOARD:
        gap = half * 0.25
        size = half - gap / 2
        for dx, dy in ((-1, -1), (1, -1), (-1, 1), (1, 1)):
            painter.drawRect(
                QRectF(
                    cx + dx * gap / 2 + (min(dx, 0) * size),
                    cy + dy * gap / 2 + (min(dy, 0) * size),
                    size,
                    size,
                )
            )
    elif item is NavItem.CONVERSATION:
        bubble = QRectF(cx - half * 0.85, cy - half * 0.65, half * 1.7, half * 1.15)
        painter.drawRoundedRect(bubble, 3, 3)
        painter.drawLine(
            QPointF(cx - half * 0.35, cy + half * 0.5), QPointF(cx - half * 0.6, cy + half * 0.9)
        )
    elif item is NavItem.MEMORY:
        painter.drawEllipse(rect.center(), half * 0.8, half * 0.8)
        painter.drawEllipse(rect.center(), half * 0.3, half * 0.3)
    elif item is NavItem.TASKS:
        for row, dy in enumerate((-0.55, 0.0, 0.55)):
            y = cy + dy * half
            width = half * (1.1 if row != 1 else 0.7)
            painter.drawLine(QPointF(cx - half * 0.75, y), QPointF(cx - half * 0.75 + width, y))
        painter.drawRect(QRectF(cx - half * 0.95, cy - half * 0.65, half * 0.3, half * 0.3))
    elif item is NavItem.SYSTEM:
        painter.drawRect(QRectF(cx - half * 0.45, cy - half * 0.45, half * 0.9, half * 0.9))
        for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            painter.drawLine(
                QPointF(cx + dx * half * 0.45, cy + dy * half * 0.45),
                QPointF(cx + dx * half * 0.9, cy + dy * half * 0.9),
            )
    elif item is NavItem.CODE:
        # "<"
        painter.drawLine(QPointF(cx - half * 0.15, cy - half * 0.5), QPointF(cx - half * 0.8, cy))
        painter.drawLine(QPointF(cx - half * 0.8, cy), QPointF(cx - half * 0.15, cy + half * 0.5))
        # ">"
        painter.drawLine(QPointF(cx + half * 0.15, cy - half * 0.5), QPointF(cx + half * 0.8, cy))
        painter.drawLine(QPointF(cx + half * 0.8, cy), QPointF(cx + half * 0.15, cy + half * 0.5))
    elif item is NavItem.SETTINGS:
        painter.drawEllipse(rect.center(), half * 0.45, half * 0.45)
        for tick in range(6):
            angle = tick * (math.pi / 3.0)
            inner = QPointF(cx + math.cos(angle) * half * 0.55, cy + math.sin(angle) * half * 0.55)
            outer = QPointF(cx + math.cos(angle) * half * 0.9, cy + math.sin(angle) * half * 0.9)
            painter.drawLine(inner, outer)


class _NavButton(QAbstractButton):
    """Self-painted nav row: icon + label, an active left accent bar
    when checked, a subtle background lift on hover. QAbstractButton
    (not QPushButton) since every visual aspect here is custom-painted —
    starting from QPushButton would mean fighting its own default chrome
    rather than building on top of nothing."""

    def __init__(self, item: NavItem, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self._item = item
        self._hovered = False
        self._accent_color = theme.ACCENT_CYAN
        self.setText(_LABELS[item])
        self.setCursor(Qt.CursorShape.PointingHandCursor)
        self.setFixedHeight(_ROW_HEIGHT)

    def set_accent_color(self, hex_color: str) -> None:
        self._accent_color = hex_color
        self.update()

    def enterEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        self._hovered = True
        self.update()
        super().enterEvent(event)

    def leaveEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        self._hovered = False
        self.update()
        super().leaveEvent(event)

    def paintEvent(self, event) -> None:  # noqa: N802 (Qt's own naming convention)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        rect = QRectF(self.rect())

        if self.isChecked():
            painter.fillRect(rect, QColor(theme.BG_PANEL_RAISED))
            accent_bar = QRectF(0, 0, _ACTIVE_BAR_WIDTH, rect.height())
            painter.fillRect(accent_bar, QColor(self._accent_color))
            text_color = QColor(self._accent_color)
        elif self._hovered and self.isEnabled():
            painter.fillRect(rect, QColor(theme.BG_PANEL_RAISED))
            text_color = QColor(theme.TEXT_PRIMARY)
        else:
            text_color = QColor(theme.TEXT_SECONDARY if self.isEnabled() else theme.TEXT_DIM)

        icon_rect = QRectF(16, (rect.height() - _ICON_SIZE) / 2, _ICON_SIZE, _ICON_SIZE)
        _paint_icon(painter, self._item, icon_rect, text_color)

        painter.setPen(text_color)
        text_left = icon_rect.right() + 12
        text_rect = QRectF(text_left, 0, rect.width() - text_left - 12, rect.height())
        alignment = int(Qt.AlignmentFlag.AlignVCenter | Qt.AlignmentFlag.AlignLeft)
        painter.drawText(text_rect, alignment, self.text())
        painter.end()


class NavigationRail(QWidget):
    """The left nav rail's full seven-row stack. See this module's own
    docstring for the page/action split."""

    page_selected = Signal(object)
    settings_requested = Signal()
    system_requested = Signal()
    code_requested = Signal()

    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 4, 0, 0)
        layout.setSpacing(2)

        self._buttons: dict[NavItem, _NavButton] = {}
        self._page_group = QButtonGroup(self)
        self._page_group.setExclusive(True)

        for item in PAGE_ITEMS:
            button = _NavButton(item)
            button.setCheckable(True)
            self._page_group.addButton(button)
            button.clicked.connect(lambda _checked, i=item: self.page_selected.emit(i))
            layout.addWidget(button)
            self._buttons[item] = button
        self._buttons[NavItem.DASHBOARD].setChecked(True)

        layout.addSpacing(14)

        system_button = _NavButton(NavItem.SYSTEM)
        system_button.clicked.connect(self.system_requested.emit)
        layout.addWidget(system_button)
        self._buttons[NavItem.SYSTEM] = system_button

        self._code_button = _NavButton(NavItem.CODE)
        self._code_button.setEnabled(False)
        self._code_button.setToolTip("Wires to Quick Commands once that panel is built.")
        self._code_button.clicked.connect(self.code_requested.emit)
        layout.addWidget(self._code_button)
        self._buttons[NavItem.CODE] = self._code_button

        settings_button = _NavButton(NavItem.SETTINGS)
        settings_button.clicked.connect(self.settings_requested.emit)
        layout.addWidget(settings_button)
        self._buttons[NavItem.SETTINGS] = settings_button

        layout.addStretch(1)

    def set_code_action_enabled(self, enabled: bool) -> None:
        """Real caller arrives with Phase 4, once MainWindow actually has
        an ActionRegistry to dispatch "Open VS Code" through."""
        self._code_button.setEnabled(enabled)
        tooltip = "" if enabled else "Wires to Quick Commands once that panel is built."
        self._code_button.setToolTip(tooltip)

    def set_accent_color(self, hex_color: str) -> None:
        """JARVIS Holographic HUD reskin, Phase 9 — sources the active-
        row accent from the mounted persona's own locked ui_accent
        (`ui/jarvis/hud_shell.py`'s one-time construction-time read)
        rather than a separately-hardcoded theme constant that only
        coincidentally matched it before this phase."""
        for button in self._buttons.values():
            button.set_accent_color(hex_color)

    def select_dashboard(self) -> None:
        """Programmatically re-check the Dashboard row — for a caller
        that needs Dashboard visually active without the user having
        clicked it (none yet in this phase; kept for the page-swap
        logic Phase 4/5 will add alongside real panel content)."""
        self._buttons[NavItem.DASHBOARD].setChecked(True)
